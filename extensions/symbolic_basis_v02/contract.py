"""A narrow symbolic structure contract; importing this module executes no data.

Models choose monomial IDs and supply an explanation. The trusted host sets the
input dimension and exact number of terms, orders coefficients canonically, and
generates every executable byte. Explanations never enter generated source.

The dictionary is exhaustive for 1..5 inputs and total degree at most three.
Equal term counts are a bookkeeping control, not equal statistical capacity.
"""

import hashlib
import itertools
import json
from pathlib import Path


SCHEMA_VERSION = "symbolic-basis-v0.2"
MAX_EXPLANATION_CHARS = 2000
CATALOG_PATH = Path(__file__).with_name("catalog.json")


def _hash_json(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False).encode("utf-8")).hexdigest()


def _catalog():
    raw = CATALOG_PATH.read_bytes()
    catalog = json.loads(raw.decode("utf-8"))
    expected = {
        "schema_version": SCHEMA_VERSION,
        "max_total_degree": 3,
        "ordering": "ascending_total_degree_then_lexicographic_exponent_tuple",
        "by_n_inputs": {},
    }
    for n in range(1, 6):
        exponents = sorted((e for e in itertools.product(range(4), repeat=n) if sum(e) <= 3), key=lambda e: (sum(e), e))
        expected["by_n_inputs"][str(n)] = [
            {"feature_id": "m_" + "_".join(map(str, e)), "exponents": list(e)}
            for e in exponents
        ]
    if catalog != expected:
        raise ValueError("catalog does not match the declared exhaustive dictionary")
    return catalog, hashlib.sha256(raw).hexdigest()


def make_spec(n_inputs, k):
    """Build the trusted host specification; bools are not integer budgets."""
    if type(n_inputs) is not int or not 1 <= n_inputs <= 5:
        raise ValueError("n_inputs must be an integer from 1 to 5")
    catalog, digest = _catalog()
    features = [item["feature_id"] for item in catalog["by_n_inputs"][str(n_inputs)]]
    if type(k) is not int or not 1 <= k <= min(16, len(features)):
        raise ValueError("k must be an integer from 1 to min(16, catalog size)")
    return {
        "schema_version": SCHEMA_VERSION,
        "n_inputs": n_inputs,
        "k": k,
        "catalog_sha256": digest,
        "feature_ids": features,
    }


def _checked_spec(spec):
    if type(spec) is not dict:
        raise ValueError("host spec must be a dictionary")
    expected = make_spec(spec.get("n_inputs"), spec.get("k"))
    if set(spec) != set(expected) or spec != expected:
        raise ValueError("host spec differs from the bound contract")
    return expected


def validate_submission(payload, spec):
    """Reject unchecked fields and return fresh data in canonical basis order."""
    expected = _checked_spec(spec)
    if type(payload) is not dict or set(payload) != {"feature_ids", "explanation"}:
        raise ValueError("submission must contain exactly feature_ids and explanation")
    features = payload["feature_ids"]
    if type(features) is not list or len(features) != expected["k"]:
        raise ValueError("feature_ids must be a list containing exactly k terms")
    if any(type(feature) is not str for feature in features):
        raise ValueError("each feature ID must be a string")
    if len(set(features)) != len(features):
        raise ValueError("duplicate feature IDs are not permitted")
    allowed = set(expected["feature_ids"])
    if any(feature not in allowed for feature in features):
        raise ValueError("feature ID is outside the host dictionary")
    constant = expected["feature_ids"][0]
    if constant not in features:
        raise ValueError("the constant feature is mandatory")
    explanation = payload["explanation"]
    if type(explanation) is not str or not explanation.strip() or len(explanation) > MAX_EXPLANATION_CHARS:
        raise ValueError("explanation must contain 1..2000 characters and non-whitespace text")
    selected = set(features)
    return {
        "spec": expected,
        "feature_ids": [feature for feature in expected["feature_ids"] if feature in selected],
        "explanation": explanation,
    }


def _source(manifest):
    n = manifest["spec"]["n_inputs"]
    features = manifest["feature_ids"]
    arguments = [f"x{i}" for i in range(n)] + ["params"]
    lines = [
        "# Generated by symbolic-basis-v0.2; parameter order is the canonical feature order.",
        "# Features: " + ", ".join(features),
        "def equation(" + ", ".join(arguments) + "):",
        "    params = np.asarray(params, dtype=float)",
        f"    if params.shape != ({len(features)},) or not np.all(np.isfinite(params)):",
        "        raise ValueError('invalid coefficient vector')",
    ]
    for i in range(n):
        lines.append(f"    x{i} = np.asarray(x{i}, dtype=float).ravel()")
    checks = ["x0.size == 0"]
    checks += [f"x{i}.shape != x0.shape" for i in range(1, n)]
    checks += [f"not np.all(np.isfinite(x{i}))" for i in range(n)]
    lines += [
        "    if " + " or ".join(checks) + ":",
        "        raise ValueError('invalid input columns')",
        "    with np.errstate(over='ignore', invalid='ignore'):",
        "        output = np.zeros_like(x0, dtype=float)",
    ]
    for index, feature in enumerate(features):
        exponents = tuple(map(int, feature[2:].split("_")))
        factors = [f"x{i}" if exponent == 1 else f"(x{i} ** {exponent})" for i, exponent in enumerate(exponents) if exponent]
        expression = f"params[{index}]" + (" * " + " * ".join(factors) if factors else "")
        lines.append(f"        output = output + {expression}")
    lines.append("    return np.nan_to_num(output, nan=0.0, posinf=1e6, neginf=-1e6)")
    return "\n".join(lines) + "\n"


def compile_submission(payload, spec):
    """Compile a checked manifest into code with one coefficient per feature.

The generated function relies on the worker's trusted ``np`` binding, accepts
the existing ``equation(input0, ..., params)`` interface, and does not fit.
Source and structure hashes exclude explanatory text intentionally.
"""
    manifest = validate_submission(payload, spec)
    source = _source(manifest)
    structure = {"spec": manifest["spec"], "feature_ids": manifest["feature_ids"]}
    return {
        **manifest,
        "source": source,
        "source_sha256": hashlib.sha256(source.encode("utf-8")).hexdigest(),
        "structural_sha256": _hash_json(structure),
        "n_params": len(manifest["feature_ids"]),
    }


def _revalidate_manifest(value):
    if type(value) is not dict:
        raise ValueError("comparison requires checked manifests")
    return validate_submission({"feature_ids": value.get("feature_ids"), "explanation": value.get("explanation")}, value.get("spec"))


def compare_structure(parent, child):
    """Describe exact feature identity changes, never scientific effectiveness.

Different k values are permitted only to label additions/removals explicitly;
they must not be pooled with the same-k exchange condition by a caller.
"""
    before = _revalidate_manifest(parent)
    after = _revalidate_manifest(child)
    if before["spec"]["n_inputs"] != after["spec"]["n_inputs"]:
        raise ValueError("cannot compare different input spaces")
    order = before["spec"]["feature_ids"]
    old = set(before["feature_ids"])
    new = set(after["feature_ids"])
    kept = [feature for feature in order if feature in old & new]
    removed = [feature for feature in order if feature in old - new]
    added = [feature for feature in order if feature in new - old]
    same_k = before["spec"]["k"] == after["spec"]["k"]
    if not added and not removed:
        label = "unchanged"
    elif same_k:
        label = "same_k_exchange"
    elif not removed:
        label = "term_addition"
    elif not added:
        label = "term_removal"
    else:
        label = "mixed_add_remove_different_k"
    return {
        "classification": label,
        "same_k": same_k,
        "parent_k": before["spec"]["k"],
        "child_k": after["spec"]["k"],
        "kept": kept,
        "removed": removed,
        "added": added,
        "claim_scope": "feature_identity_only_no_performance_or_capacity_claim",
    }

