#!/usr/bin/env python3
"""Offline SDK boundary audit: unchanged old responses plus synthetic flat fixtures.

No model configuration, credential helper, executor or saved candidate source is
executed. Socket connections are blocked before SDK import. Old annotations are
never mapped into the new contract: the fixture matrix is independently authored
and explicitly synthetic. Provider compliance cannot be established offline.
"""
import argparse
from collections import Counter
import contextlib
import copy
import hashlib
import importlib.metadata
import io
import json
import logging
import os
from pathlib import Path
import sys
from unittest.mock import patch


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_ARCHIVE = ROOT / 'artifacts/checked-feedback/2026-10-20/v02'
sys.path.insert(0, str(ROOT))
sys.dont_write_bytecode = True
EXPECTED_OUTCOMES = {'sdk_action_error_no_candidate_record': 'schema_invalid',
                     'candidate_executed': 'valid_submission',
                     'finish_tool_called': 'finish_tool',
                     'assistant_message_without_tool_calls': 'normal_assistant_message',
                     'tool_calls_finish_reason_without_tool_calls': 'incomplete_tool_response'}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def canonical(value):
    return json.dumps(value, ensure_ascii=False, allow_nan=False,
                      sort_keys=True, separators=(',', ':')).encode('utf-8')


def digest(value):
    return hashlib.sha256(value).hexdigest()


def read_json(path):
    return json.loads(path.read_text(encoding='utf-8'))


def tree_hashes(root):
    require(root.is_dir(), 'Archive directory is missing')
    result = {}
    for path in sorted(root.rglob('*')):
        require(not path.is_symlink(), 'Archive must not contain symlinks')
        if path.is_file():
            result[path.relative_to(root).as_posix()] = digest(path.read_bytes())
    require(bool(result), 'Archive is empty')
    return result


def normalize_arguments(arguments, action_type):
    """The installed SDK 1.55.1 parse/normalize path; no additional repairs."""
    from openhands.sdk.agent.utils import (
        fix_malformed_tool_arguments, normalize_tool_call, parse_tool_call_arguments,
    )
    value = parse_tool_call_arguments(arguments)
    _, value = normalize_tool_call('submit_candidate', value, ('submit_candidate', 'finish'))
    value = fix_malformed_tool_arguments(value, action_type)
    value.pop('security_risk', None)
    value.pop('summary', None)
    return value


def old_response_outcome(response, action_type):
    choices = response.get('choices')
    require(type(choices) is list and len(choices) == 1, 'Old response must contain one choice')
    choice = choices[0]
    calls = choice['message'].get('tool_calls') or []
    if not calls:
        return {'outcome': 'incomplete_tool_response' if choice['finish_reason'] == 'tool_calls'
                else 'normal_assistant_message'}
    require(len(calls) == 1, 'Expected one old tool call')
    tool = calls[0]['function']
    if tool['name'] == 'finish':
        return {'outcome': 'finish_tool'}
    require(tool['name'] == 'submit_candidate', 'Unexpected old tool name')
    try:
        arguments = normalize_arguments(tool['arguments'], action_type)
        action_type.model_validate(arguments)
    except (ValueError, TypeError, OverflowError, RecursionError) as error:
        # Only field locations and error kinds, never complete malformed values.
        failures = ([{'location': list(row['loc']), 'type': row['type']}
                     for row in error.errors()] if hasattr(error, 'errors') else [])
        return {'outcome': 'schema_invalid', 'error_type': type(error).__name__,
                'failures': failures}
    return {'outcome': 'valid_submission'}


def synthetic_fixtures():
    base = {'source': '# synthetic boundary fixture; never executed\n', 'n_params': 0,
            'rationale': 'Synthetic SDK fixture, not generated by a model.',
            'claim_id': 'e_synthetic_fixture', 'claim_op': 'eq', 'claim_value_json': '1.0',
            'prediction_id': 'e_synthetic_fixture', 'prediction_direction': 'decrease',
            'prediction_min_delta': 0.1}
    cases = [
        ('finite_scalar', {}, True, True),
        ('ordered_fact', {'claim_op': 'contains', 'claim_value_json': '["edge","$0","$1"]'}, True, True),
        ('sdk_metadata', {'summary': 17, 'security_risk': None}, True, True),
        ('invalid_json_goes_to_controller', {'claim_value_json': '{bad'}, True, True),
        ('duplicate_object_goes_to_controller', {'claim_value_json': '{"a":1,"a":2}'}, True, True),
        ('bool_value_goes_to_controller', {'claim_value_json': 'true'}, True, True),
        ('trailing_value_goes_to_controller', {'claim_value_json': '1 2'}, True, True),
        ('unknown_id_goes_to_controller', {'claim_id': 'unknown_old_id'}, True, True),
        ('semantic_enum_goes_to_controller', {'claim_op': 'unknown'}, True, False),
        ('negative_prediction_goes_to_controller', {'prediction_min_delta': -1}, True, False),
        ('old_nested_contract_rejected', {'claims': [{}], 'prediction': {}}, False, False),
        ('array_value_field_rejected', {'claim_value_json': [1]}, False, False),
        ('boolean_parameter_count_rejected', {'n_params': True}, False, False),
        ('unknown_capability_rejected', {'task_id': 'sealed'}, False, False),
    ]
    return [{'name': name, 'origin': 'synthetic_test_fixture_not_model',
             'arguments': {**copy.deepcopy(base), **changes}, 'expected_action_accepts': accepts,
             'expected_advertised_schema_accepts': advertised}
            for name, changes, accepts, advertised in cases]


def replay(archive, output):
    archive, output = Path(archive).resolve(), Path(output).resolve()
    require(not output.exists() and output.parent.is_dir(), 'Output must be a new file with an existing parent')
    require(not output.is_relative_to(archive), 'Output must be outside the immutable archive')
    before = tree_hashes(archive)
    manifest = read_json(archive / 'manifest.json')
    entries = manifest.get('archive_files')
    require(type(entries) is list and bool(entries), 'Missing archive manifest entries')
    for entry in entries:
        relative = entry['path']
        require(relative in before and before[relative] == entry['sha256'], 'Archived file hash mismatch')
    index = read_json(archive / 'request-index.json')
    require(type(index) is list and len(index) == 13, 'Expected exactly thirteen archived responses')
    report = {'version': 'offline-short-interface-v0.1', 'status': 'error',
        'purpose': 'Old-response fidelity and synthetic SDK boundary validation, not model/task performance.',
        'new_model_calls': 0, 'new_candidate_executions': 0,
        'old_annotations_repaired_or_translated': False,
        'provider_compatibility_established': False,
        'script_sha256': digest(Path(__file__).read_bytes()),
        'legacy_responses': [], 'synthetic_fixture_results': []}
    previous_logging = logging.root.manager.disable
    try:
        with contextlib.ExitStack() as stack:
            guards = [stack.enter_context(patch(target, side_effect=RuntimeError('Offline audit blocks network')))
                      for target in ('socket.socket.connect', 'socket.socket.connect_ex', 'socket.create_connection')]
            stack.enter_context(patch.dict(os.environ, {'OPENHANDS_SUPPRESS_BANNER': '1',
                'LITELLM_LOCAL_MODEL_COST_MAP': 'True', 'DO_NOT_TRACK': '1'}))
            stack.enter_context(contextlib.redirect_stdout(io.StringIO()))
            stack.enter_context(contextlib.redirect_stderr(io.StringIO()))
            logging.disable(logging.CRITICAL)
            from jsonschema import Draft202012Validator
            from rsi_eval.checked_agent import CheckedCandidateAction
            from rsi_eval.compact_agent import CompactCandidateAction
            require(importlib.metadata.version('openhands-sdk') == '1.55.1', 'SDK version must remain 1.55.1')
            report['sdk_version'] = '1.55.1'
            for row in index:
                relative = f"{row['condition']}/requests/{row['request_id']}.response.json"
                require(relative in before, 'Missing archived response')
                outcome = old_response_outcome(read_json(archive / relative), CheckedCandidateAction)
                require(outcome['outcome'] == EXPECTED_OUTCOMES[row['outcome']], 'Old response classification changed')
                report['legacy_responses'].append({'condition': row['condition'],
                    'request_id': row['request_id'], 'response_sha256': before[relative],
                    'matches_archived_outcome': True, **outcome})
            schema = CompactCandidateAction.to_mcp_schema()
            Draft202012Validator.check_schema(schema)
            require(all(value.get('type') in ('string', 'number', 'integer')
                        and not (set(value) & {'items', 'properties', 'anyOf', 'oneOf', '$ref'})
                        for value in schema['properties'].values()), 'New declaration schema must be flat primitives')
            report['compact_action_schema'] = schema
            report['compact_action_schema_sha256'] = digest(canonical(schema))
            validator = Draft202012Validator(schema)
            for fixture in synthetic_fixtures():
                try:
                    arguments = normalize_arguments(canonical(fixture['arguments']).decode('utf-8'), CompactCandidateAction)
                    CompactCandidateAction.model_validate(arguments)
                    accepted = True
                except (ValueError, TypeError, OverflowError, RecursionError):
                    accepted = False
                # The advertised schema is stricter about meaning; the runtime
                # deliberately forwards semantic errors to the trusted checker.
                advertised_args = copy.deepcopy(fixture['arguments'])
                advertised_args.pop('summary', None)
                advertised_args.pop('security_risk', None)
                advertised = validator.is_valid(advertised_args)
                require(accepted == fixture['expected_action_accepts'], 'Synthetic action result differs from contract')
                require(advertised == fixture['expected_advertised_schema_accepts'],
                        'Synthetic advertised schema result differs from contract')
                report['synthetic_fixture_results'].append({**fixture, 'action_accepts': accepted,
                                                           'advertised_schema_accepts': advertised})
            report['network_connection_attempts'] = sum(guard.call_count for guard in guards)
            require(report['network_connection_attempts'] == 0, 'Unexpected network connection attempt')
            report['legacy_outcome_counts'] = dict(Counter(row['outcome'] for row in report['legacy_responses']))
            report['synthetic_fixture_count'] = len(report['synthetic_fixture_results'])
            report['status'] = 'completed'
    except Exception as error:
        report['error_type'] = type(error).__name__
        if type(error) is ValueError:
            report['contract_failure'] = str(error)
    finally:
        logging.disable(previous_logging)
        after = tree_hashes(archive)
        report.update(archive_file_count=len(before), archive_unchanged=before == after,
                      archive_tree_before_sha256=digest(canonical(before)),
                      archive_tree_after_sha256=digest(canonical(after)))
        if before != after:
            report.update(status='error', error_type='ArchiveChanged')
        output.write_text(json.dumps(report, ensure_ascii=False, allow_nan=False, indent=2) + '\n',
                          encoding='utf-8', newline='\n')
    return report


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', type=Path, default=DEFAULT_ARCHIVE)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        report = replay(args.archive, args.output)
    except (ValueError, OSError) as error:
        print(json.dumps({'status': 'error', 'error_type': type(error).__name__,
                          'new_model_calls': 0, 'new_candidate_executions': 0}))
        return 1
    print(json.dumps({key: report.get(key) for key in ('status', 'legacy_outcome_counts',
        'synthetic_fixture_count', 'archive_file_count', 'archive_unchanged', 'network_connection_attempts',
        'new_model_calls', 'new_candidate_executions', 'error_type', 'contract_failure')}, indent=2))
    return 0 if report['status'] == 'completed' else 1


if __name__ == '__main__':
    raise SystemExit(main())
